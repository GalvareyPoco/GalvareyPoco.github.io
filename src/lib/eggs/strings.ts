export function eggStrings(lang: string): EggStrings {
  return lang.startsWith("es") ? es : lang.startsWith("fr") ? fr : en;
}

export const fill = (s: string, vars: Record<string, string | number>) => s.replace(/\{(\w+)\}/g, (_, k) => String(vars[k] ?? ""));
